"""Service-counter vocabulary candidates: which are in ASL Citizen and which in the Kaggle ISLR 250.

Reads only the split files of ASL Citizen straight from Microsoft's zip (no 42.8 GB download; uses
HTTP range requests through the `remotezip` package) and writes docs/VOCAB_CANDIDATES.md.
ASL Citizen data may not be redistributed (Microsoft Research License), so only gloss names and counts
are written, never data.

Usage:
    pip install remotezip
    python tools/vocab_candidates.py --kaggle-info models/islr_info.json
"""
import argparse
import csv
import io
import json
import re
from collections import defaultdict
from pathlib import Path

ASL_CITIZEN = "https://download.microsoft.com/download/b/8/8/b88c0bae-e6c1-43e1-8726-98cf5af36ca4/ASL_Citizen.zip"

# Draft candidates for a service counter / front desk, grouped. Edit freely; final list with NJIT ASL.
CANDIDATES = {
    "Greetings and politeness": "hello bye please thankyou sorry excuse welcome nice meet good fine ok",
    "Yes / no / understanding": "yes no not understand know dontknow again slow sign deaf hearing interpreter write",
    "Questions": "what where when who why how which howmuch",
    "People": "me my you your he we they name friend family mother father",
    "Needs and actions": "want need help have give get take buy pay sell find look go come leave stay wait finish open close start stop change return",
    "Money and shopping": "money cost price cheap expensive cards creditcard bag receipt store shop numbers",
    "Time": "now later today tomorrow yesterday morning afternoon night time minute hour day week soon",
    "Places and directions": "here there bathroom toilet restroom door office left right near far up down",
    "Health": "sick hurt pain doctor nurse medicine hospital appointment emergency",
    "Food and drink": "water food drink eat coffee hungry thirsty",
    "Travel and contact": "ticket bus train car phone call email address",
    "Describing": "good bad big small more less same different ready problem question important",
}


def asl_citizen_counts():
    from remotezip import RemoteZip
    counts, signers = defaultdict(int), defaultdict(set)
    with RemoteZip(ASL_CITIZEN) as z:
        for split in ("train", "val", "test"):
            for row in csv.DictReader(io.TextIOWrapper(z.open(f"ASL_Citizen/splits/{split}.csv"), encoding="utf-8")):
                counts[row["Gloss"]] += 1
                signers[row["Gloss"]].add(row["Participant ID"])
    return counts, signers


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--kaggle-info", required=True, help="islr_info.json (for the Kaggle 250 sign names)")
    parser.add_argument("--out", default="docs/VOCAB_CANDIDATES.md")
    args = parser.parse_args()

    kaggle = set(json.load(open(args.kaggle_info))["signs"])
    counts, signers = asl_citizen_counts()

    lines = ["# Vocabulary candidates (service counter)", "",
             "Generated by `tools/vocab_candidates.py`. **Kaggle** = in the Kaggle ISLR 250 (pretraining support). "
             "**ASL Citizen** = matching glosses (numbered glosses such as WANT1/WANT2 are different signs or variants), "
             "with videos and signers. Words in neither need our own recordings from many signers, which is expensive.", ""]
    both, only_citizen, only_kaggle, neither = [], [], [], []
    for group, words in CANDIDATES.items():
        lines += [f"## {group}", "", "| Word | Kaggle | ASL Citizen glosses (videos, signers) |", "|---|---|---|"]
        for w in words.split():
            g = sorted(x for x in counts if re.fullmatch(rf"{w.upper()}\d*", x))
            k = w in kaggle
            cit = ", ".join(f"{x} ({counts[x]}, {len(signers[x])})" for x in g) or "—"
            lines.append(f"| {w} | {'yes' if k else '—'} | {cit} |")
            (both if k and g else only_citizen if g else only_kaggle if k else neither).append(w)
        lines.append("")
    lines[4:4] = [f"Summary: {len(both)} in both, {len(only_citizen)} only in ASL Citizen, "
                  f"{len(only_kaggle)} only in Kaggle, {len(neither)} in neither "
                  f"(neither: {', '.join(neither)}). Some words are written differently in the glosses "
                  "(e.g. 'excuse me', 'how much', 'restroom'); check those by hand.", ""]
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:6]))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
